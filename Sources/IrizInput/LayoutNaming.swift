import Foundation

/// Имена раскладок для русского меню.
///
/// TIS отдаёт `kTISPropertyLocalizedName` на языке локализации ПРИЛОЖЕНИЯ,
/// а ресурсов локализации у нас нет — поэтому в русское меню приходит
/// английское «Russian». Меню, написанное на двух языках сразу, — один из
/// дефектов, за которые владелец забраковал вид (разбор снимка 10.08.2026).
///
/// Переводим только известные имена. Неизвестную раскладку оставляем как есть:
/// выдуманный перевод хуже честного оригинала, а угадывать по коду языка нельзя —
/// «ru» несут и «Русская», и «Русская — ПК», это разные раскладки.
public enum LayoutNaming {
    /// Оба тире (U+2013 у Apple и обычный дефис) — TIS отдаёт разное на разных версиях.
    private static let russian: [String: String] = [
        "Russian": "Русская",
        "Russian – PC": "Русская — ПК",
        "Russian - PC": "Русская — ПК",
        "Russian – Phonetic": "Русская — фонетическая",
        "Russian - Phonetic": "Русская — фонетическая",
        "U.S.": "Американская",
        "US": "Американская",
        "US International – PC": "Американская — международная",
        "British": "Британская",
        "Ukrainian": "Украинская",
        "Ukrainian – PC": "Украинская — ПК",
        "Belarusian": "Белорусская",
        "Kazakh": "Казахская",
        "Tatar": "Татарская",
    ]

    /// «Russian» → «Русская». «ABC» → «ABC»: это имя собственное, а не английское слово.
    public static func russianName(_ name: String) -> String {
        russian[name] ?? name
    }
}

// Готовые своды правил для формы промпта.
//
// Владелец 07.09.2026: «там, где вставь свой промпт или свои правила,
// необходимо, чтобы там в том числе был режим, который ты подготовишь. Это
// идеальный промпт, исходя из тех данных, которые у тебя есть. Как писать
// правильный промпт? Туда должно быть идеально по версии Anthropic, по версии
// OpenAI или по версии GitHub».
//
// Что это НЕ такое. Это не «секретный промпт от вендора»: у вендоров таких
// файлов нет, а выдумать и подписать чужим именем значило бы соврать. Это
// свод правил, который каждый из них публикует в своей документации по
// промпт-инжинирингу, изложенный одним абзацем и приведённый к тому, что
// умеет наш промпт-режим: он задаёт ФОРМУ, а не право выдумывать факты.
//
// Поэтому имя набора называет ИСТОЧНИК правил, а не автора текста, и каждый
// набор несёт ссылку на документ, из которого правила взяты.
import Foundation

public struct PromptGuidancePreset: Equatable, Sendable, Identifiable {
    public let id: String
    public let title: String
    /// Откуда взяты правила. Ссылка обязательна: свод без источника проверить
    /// нечем, а «идеальный промпт по версии X» без X - просто чужое имя.
    public let source: String
    public let instructions: String

    public init(id: String, title: String, source: String, instructions: String) {
        self.id = id
        self.title = title
        self.source = source
        self.instructions = instructions
    }
}

public enum PromptGuidancePresets {
    public static let anthropic = PromptGuidancePreset(
        id: "anthropic",
        title: "По правилам Anthropic",
        source: "docs.anthropic.com/en/docs/build-with-claude/prompt-engineering",
        instructions: """
        Ставь задачу первой строкой, до всякого контекста. \
        Дальше давай контекст отдельным блоком и помечай его тегом вида <контекст>. \
        Называй роль исполнителя одним предложением, если она меняет ответ. \
        Проси рассуждать по шагам там, где вывод неочевиден, и отделяй рассуждение от ответа. \
        Задавай точный формат ответа: длину, структуру, чего в ответе быть не должно. \
        Пиши положительными указаниями: «сделай так», а не «не делай эдак».
        """
    )

    public static let openai = PromptGuidancePreset(
        id: "openai",
        title: "По правилам OpenAI",
        source: "platform.openai.com/docs/guides/prompt-engineering",
        instructions: """
        Формулируй задачу конкретно: что сделать, для кого, в каком виде. \
        Разделяй инструкцию и данные явным разделителем, например ###. \
        Показывай пример желаемого ответа, если форма важнее содержания. \
        Проси сначала план, потом результат, когда шагов больше трёх. \
        Указывай, что делать при нехватке данных: спросить, а не додумывать. \
        Убирай лишние вежливости — они занимают место и ничего не уточняют.
        """
    )

    public static let github = PromptGuidancePreset(
        id: "github",
        title: "По правилам GitHub",
        source: "docs.github.com/en/copilot/using-github-copilot/prompt-engineering",
        instructions: """
        Начинай с общей цели, потом сужай до конкретного шага. \
        Называй язык, фреймворк и версию, если задача про код. \
        Давай пример входа и ожидаемого выхода вместо описания словами. \
        Дроби большую задачу на части и проси делать их по очереди. \
        Проси проверяемый результат: тест, команду или критерий приёмки. \
        Повторяй важное ограничение в конце: оно теряется в середине текста.
        """
    )

    public static let all: [PromptGuidancePreset] = [anthropic, openai, github]
}

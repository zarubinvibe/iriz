// Очистка речи: два пути и один шов между ними.
//
// Владелец: «я все-таки хочу добавить функционал, когда речь чистится. Продумать,
// это можно сделать локально, и если это невозможно, как это можно делать, чтобы
// делать где-то снаружи».
//
// Отсюда ровно три состояния, и третьего не бывает:
//
//   ВЫКЛ      текст идёт как распознан. Умолчание не здесь: очистка полезна.
//   ВНУТРИ    правила работают на этой машине, наружу не уходит ничего.
//             Это умолчание.
//   СНАРУЖИ   текст уезжает агенту. Только по явному включению, и в продукте
//             это видно надписью ДО того, как что-то ушло.
//
// ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА. Обычная диктовка наружу не уходит никогда, кроме
// режима СНАРУЖИ, включённого руками владельца. Это условие старше любой пользы
// от лучшего качества очистки, и держит его проба, а не комментарий.
//
// Цена ошибки несимметрична, и она задаёт строгость правил. Оставленная запинка
// стоит владельцу секунды на правку. Съеденное очисткой слово в процессуальном
// документе меняет смысл утверждения, и заметит он это в суде, а не в редакторе.
// Поэтому правило, которое режет смысл в редком случае, ХУЖЕ отсутствующего.
import Foundation

/// Где чистится речь.
public enum SpeechCleanupMode: String, CaseIterable, Codable, Sendable {
    case off
    case local
    case external

    public var title: String {
        switch self {
        case .off: return "Не чистить"
        case .local: return "На этой машине"
        case .external: return "Внешним агентом"
        }
    }

    /// Уходит ли текст с машины. Спрашивается кодом, а не человеком по памяти:
    /// на этот вопрос завязано предупреждение в продукте и проба границы.
    public var sendsTextOutside: Bool {
        self == .external
    }

    /// Что владелец обязан прочитать до включения. Пустое там, где ничего не
    /// уходит: предупреждение без повода приучает не читать предупреждения.
    public var warning: String? {
        guard sendsTextOutside else { return nil }
        return "Надиктованный текст будет уходить внешнему агенту. Обычная диктовка "
            + "без этого режима с машины не уходит."
    }
}

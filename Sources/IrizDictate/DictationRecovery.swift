// Спасение надиктовки, которая никуда не вставилась — решения, без AppKit.
//
// Зачем этап. Провал доставки уже был смоделирован честно (см.
// TextInsertionVerdict), но реакция на него была одна: строка в логе и жёлтая
// плашка «!» на полторы секунды. Текст при этом жив — сырьё лежит на диске, —
// однако дорога к нему одна: вспомнить хоткей истории. Владелец диктует в поле,
// поле осталось пустым, и приложение говорит «не получилось», не показывая ЧТО
// именно не получилось вставить. Этот файл решает, когда поднимать окно с
// готовым текстом, а когда молчать.
//
// Почему решения здесь, а не в колбэках AppKit: живое окно, живой буфер и
// защищённый ввод под `swift test` не наблюдаются. Решение, спрятанное в
// колбэке, проверить нечем, а зелёный гейт над непроверяемой логикой — гейт,
// который врёт.
import Foundation

/// Почему окно спасения не поднялось. Причина уходит в лог: молчание без
/// названной причины неотличимо от забытой ветки.
enum DictationRecoverySilence: String, Equatable {
    /// Текст в поле — спасать нечего.
    case delivered
    /// Вердикт ещё не окончательный, окно ожидания не истекло.
    case verdictNotFinal
    /// Сработал прямой ввод юникодом: текст, скорее всего, УЖЕ в поле.
    case mayHaveBeenInserted
    /// Показывать нечего: пустая строка.
    case nothingToShow
    /// Владелец выключил окно в настройках.
    case turnedOff
}

/// Что делать с провалом доставки.
enum DictationRecoveryPresentation: Equatable {
    case stayQuiet(DictationRecoverySilence)
    case rescueWindow(TextInsertionFailure)
}

/// Поднимать ли окно спасения.
///
/// КЛЮЧЕВОЕ РЕШЕНИЕ ЭТАПА — `.deliveryNotObservable`. Этот класс провала
/// возвращается, когда сработала запасная стратегия «прямой ввод юникодом»
/// (TextInserter.swift, DirectUnicodeInserter): все события набора отправлены
/// успешно, но канала наблюдения у этого пути нет по устройству — никто не
/// «запрашивает текст» у провайдера буфера, потому что буфер не участвует.
/// То есть текст скорее ВСТАВЛЕН, чем нет; неизвестен не результат, а способ
/// его подтвердить.
///
/// Поэтому здесь — молчание. Окно «не доставлено» поверх удавшейся вставки
/// хуже, чем тишина, по трём причинам:
///   1) оно зовёт нажать «вставить ещё раз» — и абзац уедет в документ дважды,
///      а это иск, поданный с задвоенным абзацем;
///   2) оно зовёт NSApp.activate и выдёргивает фокус ровно в тот момент, когда
///      владелец продолжает печатать в поле, куда текст уже попал;
///   3) окно, которое врёт через раз, перестают читать — и оно не сработает
///      тогда, когда провал настоящий.
/// Страховка на этот случай остаётся прежней и достаточной: сырьё на диске,
/// знак на плашке, окно истории по хоткею.
///
/// `.waiting` окном тоже не разворачивается: это не исход, а «ещё ждём».
/// Живьём его сюда не приносят (confirmDelivery крутится до окончательного
/// вердикта), но ветка названа явно — молчаливый `default` на неокончательном
/// вердикте однажды показал бы окно посреди удачной вставки.
func dictationRecoveryPresentation(verdict: TextInsertionVerdict,
                                   rescueEnabled: Bool,
                                   hasText: Bool) -> DictationRecoveryPresentation {
    switch verdict {
    case .delivered:
        return .stayQuiet(.delivered)
    case .waiting:
        return .stayQuiet(.verdictNotFinal)
    case .notDelivered(let failure):
        // Порядок проверок = от самой сильной правды к самой слабой: причина в
        // логе должна называть то, что действительно решило исход, а не первый
        // подвернувшийся флаг.
        if failure == .deliveryNotObservable { return .stayQuiet(.mayHaveBeenInserted) }
        guard hasText else { return .stayQuiet(.nothingToShow) }
        guard rescueEnabled else { return .stayQuiet(.turnedOff) }
        return .rescueWindow(failure)
    }
}

/// Текст, который собирались вставить, и причина, по которой он остался тут.
///
/// Текст ИМЕННО обработанный — тот, что уходил в поле после словаря замен и
/// суффикса. Не сырьё ASR: `inserted.txt` пишется только по подтверждённой
/// доставке, поэтому история на провале откатывается к сырью, а сырьё — это
/// чужая фамилия в том виде, как её послышало распознавание. Отдать её
/// владельцу в окне «вот ваш текст» значит отдать её дальше в документ.
///
/// Приложения-получателя здесь нет и быть не должно — ни поля, ни лога, ни
/// файла. Куда именно диктовал пользователь, приложение не запоминает.
struct DictationRescue: Equatable {
    let text: String
    let failure: TextInsertionFailure
}

/// Заголовок окна спасения.
let DICTATION_RESCUE_TITLE = "Текст не попал в поле"

/// Что именно случилось — одной строкой, без жаргона вердиктов.
func dictationRescueExplanation(for failure: TextInsertionFailure) -> String {
    switch failure {
    case .insertionFailed:
        return "Не сработали обе попытки: ни через буфер обмена, ни прямым вводом."
    case .targetNeverRequestedText:
        return "Вставка ушла, но поле её не забрало. Текст цел — он здесь."
    case .deliveryNotObservable:
        // До окна этот класс не доходит (см. dictationRecoveryPresentation), но
        // ветка обязана быть честной: молчаливый провал в switch однажды выдаст
        // владельцу пустую строку вместо объяснения.
        return "Текст ввели напрямую — подтвердить доставку было нечем."
    }
}

/// Чем кончилась попытка «вставить ещё раз».
///
/// Нужно потому, что окно спасения — единственная копия текста: на диске его
/// нет (`inserted.txt` пишется только по подтверждённой доставке). Молчаливая
/// неудача повтора при закрытом окне стоила бы владельцу надиктовки целиком,
/// поэтому у каждой неудачи есть строка, а окно возвращается на экран.
enum DictationRescueRetryOutcome: String, Equatable {
    /// Неизвестно, в какое приложение вставлять.
    case unknownTarget
    /// Фокус не успел вернуться вызывающему за отведённое окно.
    case focusDidNotReturn
    /// Вставили — поле снова не забрало.
    case notDelivered
}

func dictationRescueRetryNotice(_ outcome: DictationRescueRetryOutcome) -> String {
    switch outcome {
    case .unknownTarget:
        return "Непонятно, куда вставлять — приложение мы не запоминаем. Скопируйте текст."
    case .focusDidNotReturn:
        return "Фокус не вернулся в поле, вставлять было некуда. Скопируйте текст."
    case .notDelivered:
        return "Поле снова не приняло вставку. Скопируйте и вставьте руками."
    }
}

// MARK: - Клавиши в режиме спасения

/// Что делает нажатие, когда на экране окно спасения. Раскладка та же, что в
/// истории (`dictationHistoryKeyAction`), но цель другая: список под окном не
/// показывается, значит ⏎ и ⌘C относятся к спасённому тексту, а не к выделенной
/// записи. Решение вынесено из монитора событий, чтобы проверялось тестом.
enum DictationRescueKeyOutcome: Equatable {
    case insertRescueText
    case copyRescueText
    case close
    /// Стрелки и всё прочее: двигать нечего.
    case ignore
}

func dictationRescueKeyOutcome(_ action: DictationHistoryKeyAction) -> DictationRescueKeyOutcome {
    switch action {
    case .insertSelected: return .insertRescueText
    case .copySelected: return .copyRescueText
    case .close: return .close
    case .moveSelection, .passThrough: return .ignore
    }
}

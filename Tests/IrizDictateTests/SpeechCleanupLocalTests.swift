// Проба локальной очистки: что снимаем и что обязаны не тронуть.
//
// Половина проб ниже - контрпримеры из враждебного разбора. Они стоят здесь
// потому, что на них «очевидное» правило стирает идентификатор или ссылку на
// норму, а текст остаётся грамматически гладким: глазами такое не ловится.
//
// Вторая половина - поправка владельца. Разбор судил письменный юридический
// текст, а на вход приходит распознанная речь: «ЭЭ» вместо «электроэнергии» в
// расшифровке взяться неоткуда, потому что так не говорят.
import Foundation
import Testing

@testable import IrizDictate

@Suite("Локальная очистка речи")
struct SpeechCleanupLocalTests {
    // MARK: - Снимаем

    @Test("растянутое э снимается вместе со своей запятой")
    func растянутоеЭСнимается() {
        #expect(speechCleanupLocal("Ответчик, э-э, не представил акт сверки.")
                == "Ответчик не представил акт сверки.")
    }

    @Test("ммм снимается")
    func мммСнимается() {
        #expect(speechCleanupLocal("Срок, ммм, истекал 12 марта.")
                == "Срок истекал 12 марта.")
    }

    @Test("эм снимается, когда рядом нет ни буквы перечня, ни числа")
    func эмСнимается() {
        #expect(speechCleanupLocal("Мы, эм, направили претензию 3 июня.")
                == "Мы направили претензию 3 июня.")
    }

    @Test("растянутое ну снимается")
    func растянутоеНуСнимается() {
        #expect(speechCleanupLocal("Мы, ну-у, готовы обсудить мировое соглашение.")
                == "Мы готовы обсудить мировое соглашение.")
    }

    @Test("начальное Ну снимается и следующее слово поднимается")
    func начальноеНуСнимается() {
        #expect(speechCleanupLocal("Ну и что тут скажешь.") == "Что тут скажешь.")
    }

    @Test("повтор слова схлопывается")
    func повторСхлопывается() {
        #expect(speechCleanupLocal("Мы подали подали иск.") == "Мы подали иск.")
    }

    // MARK: - Не трогаем: названная вслух буква

    @Test("буква подпункта не снимается")
    func букваПодпунктаНеСнимается() {
        // Контрпример разбора: «э» - штатная буква буквенных перечней НК и ГК.
        // Удаление молча переадресует ссылку на другую норму.
        let text = "Расходы учитываются по норме э пункта 1 статьи 265 НК РФ."
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("буква в подпункте не снимается")
    func букваВПодпунктеНеСнимается() {
        let text = "в подпункте эм пункта 2 договора"
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("буква государственного знака не снимается")
    func букваЗнакаНеСнимается() {
        // Рядом числа: это государственный регистрационный знак, а не звук.
        let text = "Знак Т 512 эм 116 зафиксирован камерой."
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("прописная форма не трогается")
    func прописнаяНеТрогается() {
        // Прописные в расшифровке означают, что человек назвал аббревиатуру по
        // буквам намеренно.
        let text = "Договор поставки ЭЭ подписан."
        #expect(speechCleanupLocal(text) == text)
    }

    // MARK: - Не трогаем: чужие слова

    @Test("внутри кавычек не чистится ничего")
    func внутриКавычекНеЧистится() {
        // Чужие слова цитируются как сказаны: правка внутри цитаты меняет
        // показания.
        let text = "Свидетель показал: «Ну, э-э, я в тот день не выезжал»."
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("вложенные кавычки не обрывают защиту")
    func вложенныеКавычкиНеОбрываютЗащиту() {
        // Наивный счёт «первая открывающая - первая закрывающая» обрывал защиту
        // на внутренней кавычке, и хвост показаний оставался голым.
        let text = "Свидетель показал: «Я работал в ООО «Ромашка», и, э-э, не выезжал»."
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("строка прямой речи защищена целиком")
    func прямаяРечьЗащищена() {
        let text = "- Э-э, я не помню, - ответил свидетель."
        #expect(speechCleanupLocal(text) == text)
    }

    // MARK: - Не трогаем: осмысленные повторы

    @Test("усиление повтором не считается")
    func усилениеНеПовтор() {
        let text = "Это очень очень важно для дела."
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("отрицание не схлопывается")
    func отрицаниеНеСхлопывается() {
        // «не не» меняет утверждение на противоположное.
        let text = "Он не не подписывал акт."
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("знак между словами защищает пару")
    func знакМеждуЗащищает() {
        let text = "Иванов, Иванов и Петров подписали акт."
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("второй с заглавной - потерянная точка, не повтор")
    func второйСЗаглавнойНеПовтор() {
        let text = "рассмотрено дело Дело передано в апелляцию"
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("числа повтором не считаются")
    func числаНеПовтор() {
        let text = "квартира два два в доме 5"
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("ну-ну не трогается")
    func нуНуНеТрогается() {
        // Устойчивое сочетание двух полных слов: удаление переворачивает тон
        // письма доверителю.
        let text = "Ну-ну, посмотрим, что скажет экспертиза."
        #expect(speechCleanupLocal(text) == text)
    }

    @Test("чистый текст не меняется")
    func чистыйТекстНеМеняется() {
        let text = "Истец просит взыскать 120 000 рублей и проценты."
        #expect(speechCleanupLocal(text) == text)
    }
}
